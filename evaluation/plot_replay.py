#!/usr/bin/env python3
"""Plot the seeded simulated loss of legitimate late packets vs replay bitmap width."""
import argparse
import csv
from collections import defaultdict
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('csv', type=Path, help='CSV generated by build/replay_study')
    parser.add_argument('--out', type=Path, default=Path('evaluation/replay-window.png'))
    args = parser.parse_args()
    with args.csv.open(newline='', encoding='utf-8') as handle:
        rows = list(csv.DictReader(handle))
    grouped = defaultdict(lambda: [0, 0, 0])
    for row in rows:
        k = (int(row['max_delay_ticks']), int(row['window']))
        grouped[k][0] += int(row['originals'])
        grouped[k][1] += int(row['late_originals'])
        grouped[k][2] += int(row['accepted_duplicates'])
    if not grouped or any(n[2] != 0 for n in grouped.values()):
        raise SystemExit('Missing data or duplicate-rejection invariant failed')
    try:
        import matplotlib.pyplot as plt
    except ImportError as exc:
        raise SystemExit('Install matplotlib (python3 -m pip install matplotlib)') from exc
    fig, ax = plt.subplots(figsize=(8.5, 5))
    widths = sorted({w for _, w in grouped})
    for delay in sorted({d for d, _ in grouped}):
        drop = [(100 * grouped[(delay, w)][1] / grouped[(delay, w)][0])
                for w in widths]
        ax.plot(widths, drop, marker='o', label=f'max delay: {delay} ticks')
    ax.axvline(128, linestyle='--', linewidth=1, label='implemented window (128)')
    ax.set_xscale('log', base=2)
    ax.set_xticks(widths, [str(w) for w in widths])
    ax.set_xlabel('Anti-replay window size (packets)')
    ax.set_ylabel('Late legitimate packets rejected (%)')
    ax.set_title('Seeded synthetic arrivals — 4,096 packets × 5 seeds per setting')
    ax.legend(loc='best', fontsize=8)
    ax.grid(alpha=0.25)
    fig.tight_layout()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(args.out, dpi=180)
    print('Wrote', args.out)
    for width in widths:
        num = grouped[(128, width)]
        print(f'128-tick delay: window={width}, dropped={num[1]}/{num[0]} '
              f'({num[1] / num[0]:.1%}), bitmap={width // 8} bytes')


if __name__ == '__main__':
    main()
